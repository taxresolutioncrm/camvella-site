import fs from 'node:fs';
import path from 'node:path';
const root=path.resolve(process.cwd(),'health-preview');
const read=p=>fs.readFileSync(path.join(root,p),'utf8');
const app=read('index.html');
const site=read('site.html');
const names=['001_core_schema.sql','002_comms_revenue_audit.sql','003_rls.sql','004_storage.sql','005_platform_support.sql','006_app_support.sql','007_data_api_grants.sql'];
const mig=Object.fromEntries(names.map(f=>[f,read('supabase/migrations/'+f)]));
const allMig=Object.values(mig).join('\n');
const failures=[];
for(const fn of ['email','phone','sms','fax','voicemail','inbox','integration','lab']) if(!app.includes('function '+fn+'()')) failures.push('missing view '+fn);
if(!app.includes('groupToggle')||!app.includes('health-crm-sidebar-groups-v1')) failures.push('collapsible sidebar missing');
if(!app.includes('actionModal')||!app.includes('health-crm-sandbox-actions')) failures.push('interactive sandbox actions missing');
for(const secret of ['service_role','sb_secret_']) if(app.includes(secret)) failures.push('frontend secret marker '+secret);
const tables=[...allMig.matchAll(/create table public\.([a-z0-9_]+)/g)].map(m=>m[1]);
const rls=mig['003_rls.sql']+mig['005_platform_support.sql']+mig['006_app_support.sql'];
for(const t of tables) if(!rls.includes('alter table public.'+t+' enable row level security')) failures.push('RLS enable missing '+t);
for(const p of [...rls.matchAll(/create policy [\s\S]*?for update[\s\S]*?;/g)].map(m=>m[0])) if(!p.toLowerCase().includes('with check')) failures.push('update policy missing WITH CHECK');
for(const v of [...mig['005_platform_support.sql'].matchAll(/create view public\.([a-z0-9_]+)[\s\S]*?;/g)].map(m=>m[0])) if(!v.includes('security_invoker = true')) failures.push('security_invoker missing view');
for(const op of ['select','insert','update','delete']) if(!mig['004_storage.sql'].includes('for '+op+' to authenticated')) failures.push('storage policy missing '+op);
if(!mig['007_data_api_grants.sql'].includes('revoke all on all tables in schema public from anon')) failures.push('anon grant revoke missing');
if(!mig['007_data_api_grants.sql'].includes('grant usage on schema public to authenticated')) failures.push('authenticated schema grant missing');
if(!site.includes('noindex,nofollow')) failures.push('preview site must remain noindex');
if(!site.includes('SoftwareApplication')) failures.push('website schema missing');
console.log(JSON.stringify({tables:tables.length,migrations:names.length,failures},null,2));
if(failures.length) process.exit(1);
